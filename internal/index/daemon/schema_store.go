func validatePublishKey(key []byte) (bool, error) {
	parsed, err := schema.ParseKey(key)
	if err != nil {
		return false, err
	}
	switch parsed.Kind {
	case schema.KeyBlob, schema.KeyInodeRevision, schema.KeyDirectoryRevision, schema.KeySnapshot:
		return true, nil
	case schema.KeyPack, schema.KeyPackAggregate, schema.KeyTierAggregate, schema.KeyReverseManifest, schema.KeyReverseInode,
		schema.KeyReferenceCount, schema.KeyGarbageCollection, schema.KeyCrawlDebt, schema.KeyImportCheckpoint,
		schema.KeySnapshotImportCheckpoint, schema.KeyExportCheckpoint,
		schema.KeyPackHistoryBucket, schema.KeyHistoryRawFloor, schema.KeyHistoryEnabledAt,
		schema.KeyPackPlacement, schema.KeyBackendPack, schema.KeyPlacementDeleteQueue, schema.KeyPlacementRequest, schema.KeyRepackLineage, schema.KeyPromotionEligibility, schema.KeyAnalyticsFact, schema.KeyAnalyticsCache, schema.KeyAnalyticsMetadata, schema.KeyAnalyticsBuildCheckpoint, schema.KeyPathVersion:
		return false, nil
	case schema.KeyPackHistory:
		return true, nil
	case schema.KeyContentManifest:
		return false, fmt.Errorf("content manifests require CreateContentManifest")
	case schema.KeyNextRevision:
		return false, fmt.Errorf("revision sequence requires AllocateRevision")
	default:
		return false, fmt.Errorf("schema key requires a dedicated transactional operation")
	}
}

// MarkExportPending durably exposes a legacy snapshot whose authoritative
// scope has not yet been committed.
func (store *SchemaStore) MarkExportPending(ctx context.Context, snapshotID schema.ID, rootKey []byte) error {
	record := schema.ExportCheckpointRecord{State: schema.ExportPending, RootKey: append([]byte(nil), rootKey...)}
	encoded, err := record.MarshalBinary()
	if err != nil {
		return err
	}
	return store.Put(ctx, schema.ExportCheckpointKey(snapshotID), encoded, true)
}

func (store *SchemaStore) MarkExportFailed(ctx context.Context, snapshotID schema.ID, failure error) error {
	key := schema.ExportCheckpointKey(snapshotID)
	value, found, err := store.Get(ctx, key)
	if err != nil {
		return err
	}
	if !found {
		return fmt.Errorf("snapshot export checkpoint is missing")
	}
	record, err := schema.UnmarshalExportCheckpointRecord(value)
	if err != nil {
		return err
	}
	if record.State != schema.ExportPending {
		return fmt.Errorf("snapshot export cannot fail from state %d", record.State)
	}
	record.State = schema.ExportFailed
	record.Attempts++
	record.LastError = failure.Error()
	encoded, err := record.MarshalBinary()
	if err != nil {
		return err
	}
	return store.Put(ctx, key, encoded, true)
}

// PublishSnapshotScope verifies that the reconciled root is durable, allocates
// a commit sequence, creates the immutable snapshot record, and completes its
// export checkpoint in one serializable transaction.
func (store *SchemaStore) PublishSnapshotScope(ctx context.Context, scope SnapshotScope) error {
	root, err := schema.ParseKey(scope.RootKey)
	if err != nil || root.Kind != schema.KeyDirectoryRevision || root.Revision == 0 || scope.SnapshotID == (schema.ID{}) {
		return fmt.Errorf("invalid snapshot scope")
	}
	if scope.Crawl != nil && (scope.Crawl.RootFSID != root.FSID || scope.Crawl.RootInode != root.Inode) {
		return fmt.Errorf("authoritative crawl root does not match snapshot root")
	}
	var identities []schema.ParsedKey
	if enabled, enabledErr := store.analyticsEnabled(ctx); enabledErr != nil {
		return enabledErr
	} else if enabled {
		identities, err = store.snapshotIdentities(ctx, scope.RootKey)
		if err != nil {
			return err
		}
	}
	bindings, err := store.authoritativeScopeBindings(ctx, scope.Crawl)
	if err != nil {
		return err
	}
	crawlIdentities := identities
	if scope.Crawl != nil {
		crawlIdentities, err = store.snapshotObservedIdentities(ctx, scope.RootKey)
		if err != nil {
			return err
		}
	}
	backoff := 100 * time.Microsecond
	for range revisionAllocationAttempts {
		err := store.publishSnapshotScopeOnce(ctx, scope, root, identities, crawlIdentities, bindings)
		if status.Code(err) != codes.Aborted {
			return err
		}
		timer := time.NewTimer(backoff)
		select {
		case <-ctx.Done():
			timer.Stop()
			return ctx.Err()
		case <-timer.C:
		}
		backoff = min(backoff*2, 25*time.Millisecond)
	}
	return fmt.Errorf("publish snapshot scope: transaction conflict retry limit exceeded")
}

func (store *SchemaStore) publishSnapshotScopeOnce(ctx context.Context, scope SnapshotScope, root schema.ParsedKey, identities, crawlIdentities []schema.ParsedKey, bindings map[string]schema.AuthoritativeSourceBindingRecord) error {
	transaction, err := store.client.Begin(ctx)
	if err != nil {
		return err
	}
	fail := func(err error) error { rollbackTransaction(ctx, transaction); return err }
	if _, found, err := transaction.Get(ctx, scope.RootKey); err != nil {
		return fail(err)
	} else if !found {
		return fail(fmt.Errorf("snapshot root revision is not durable"))
	}
	checkpointKey := schema.ExportCheckpointKey(scope.SnapshotID)
	if value, found, err := transaction.Get(ctx, checkpointKey); err != nil {
		return fail(err)
	} else if !found {
		return fail(fmt.Errorf("snapshot export checkpoint is missing"))
	} else if checkpoint, decodeErr := schema.UnmarshalExportCheckpointRecord(value); decodeErr != nil || checkpoint.State != schema.ExportPending {
		if decodeErr != nil {
			return fail(decodeErr)
		}
		return transaction.Rollback(ctx)
	}
	nextKey := schema.NextRevisionKey()
	next := uint64(1)
	if value, found, err := transaction.Get(ctx, nextKey); err != nil {
		return fail(err)
	} else if found {
		next, err = schema.UnmarshalNextRevision(value)
		if err != nil {
			return fail(err)
		}
	}
	if next == math.MaxUint64 {
		return fail(fmt.Errorf("repository revision sequence exhausted"))
	}
	record := schema.SnapshotRecord{CommitSequence: next, RootFSID: root.FSID, RootInode: root.Inode, RootRevision: root.Revision, OriginalJSON: append([]byte(nil), scope.OriginalJSON...)}
	snapshotValue, err := record.MarshalBinary()
	if err != nil {
		return fail(err)
	}
	snapshotCommitValue, err := (schema.SnapshotCommitRecord{SnapshotTimeUnixNano: snapshotTimeUnixNano(scope.OriginalJSON), RootKey: append([]byte(nil), scope.RootKey...)}).MarshalBinary()
	if err != nil {
		return fail(err)
	}
	checkpointValue, err := (schema.ExportCheckpointRecord{State: schema.ExportComplete, CommitSequence: next, Attempts: 1, RootKey: scope.RootKey}).MarshalBinary()
	if err != nil {
		return fail(err)
	}
	nextValue, err := schema.MarshalNextRevision(next + 1)
	if err != nil {
		return fail(err)
	}
	puts := []Mutation{
		{Key: schema.SnapshotKey(scope.SnapshotID), Value: snapshotValue},
		{Key: schema.SnapshotCommitKey(next, scope.SnapshotID), Value: snapshotCommitValue},
		{Key: checkpointKey, Value: checkpointValue}, {Key: nextKey, Value: nextValue},
	}
	crawlGenerations := map[identityKey]uint64{}
	if scope.Crawl != nil {
		for _, identity := range crawlIdentities {
			generation := identity.Revision
			if _, prior, found := currentSourceBinding(bindings, identity.FSID, identity.Inode); found && prior.State == schema.AuthoritativeSourceLive {
				generation = prior.Generation
			}
			crawlGenerations[identityKey{identity.FSID, identity.Inode}] = generation
		}
	}
	analyticsGeneration := uint64(0)
	deltaOrdinal := uint32(0)
	if metadataValue, found, getErr := transaction.Get(ctx, schema.AnalyticsMetadataKey()); getErr != nil {
		return fail(getErr)
	} else if found {
		metadata, decodeErr := schema.UnmarshalAnalyticsMetadataRecord(metadataValue)
		if decodeErr == nil && metadata.Enabled {
			analyticsGeneration = metadata.Generation
			for _, identity := range identities {
				generation := identity.Revision
				if crawlGeneration := crawlGenerations[identityKey{identity.FSID, identity.Inode}]; crawlGeneration != 0 {
					generation = crawlGeneration
				}
				delta := schema.AnalyticsDeltaRecord{Kind: schema.AnalyticsDeltaRetainedReferences, FSID: identity.FSID, Inode: identity.Inode, IdentityGeneration: generation, Revision: next, State: schema.AnalyticsUnknown, RetainedSnapshotRefs: 1, ReferenceOperation: schema.AnalyticsReferencesIncrement, ClassificationEpoch: metadata.Generation}
				encoded, encodeErr := delta.MarshalBinary()
				if encodeErr != nil {
					return fail(encodeErr)
				}
				puts = append(puts, Mutation{Key: schema.AnalyticsDeltaKey(next, deltaOrdinal), Value: encoded})
				deltaOrdinal++
			}
		}
	}
	if scope.Crawl != nil {
		crawlPuts, err := store.authoritativeCrawlMutations(ctx, transaction, *scope.Crawl, crawlIdentities, bindings, next, analyticsGeneration)
		if err != nil {
			return fail(err)
		}
		for _, mutation := range crawlPuts {
			if parsed, parseErr := schema.ParseKey(mutation.Key); parseErr == nil && parsed.Kind == schema.KeyAnalyticsDelta {
				mutation.Key = schema.AnalyticsDeltaKey(next, deltaOrdinal)
				deltaOrdinal++
			}
			puts = append(puts, mutation)
		}
	}
	if err := writeTransactionBatches(ctx, transaction, store.client.Limits(), puts, nil); err != nil {
		return fail(err)
	}
	if err := transaction.Commit(ctx); err != nil {
		rollbackTransaction(ctx, transaction)
		return err
	}
	return nil
}

type identityKey struct {
	fsid  uint32
	inode uint64
}

func (store *SchemaStore) authoritativeScopeBindings(ctx context.Context, claim *AuthoritativeCrawlClaim) (map[string]schema.AuthoritativeSourceBindingRecord, error) {
	result := map[string]schema.AuthoritativeSourceBindingRecord{}
	if claim == nil {
		return result, nil
	}
	if claim.ScopeID == (schema.ID{}) || claim.RootFSID == 0 || claim.RootInode == 0 || claim.StartFence == 0 {
		return nil, fmt.Errorf("invalid authoritative crawl claim")
	}
	prefix := schema.AuthoritativeSourceBindingPrefix(claim.ScopeID)
	var after []byte
	for {
		entries, done, err := store.ScanPrefix(ctx, prefix, after, 10_000)
		if err != nil {
			return nil, err
		}
		for _, entry := range entries {
			record, err := schema.UnmarshalAuthoritativeSourceBindingRecord(entry.Value)
			if err != nil {
				return nil, err
			}
			result[string(entry.Key)] = record
		}
		if done {
			return result, nil
		}
		if len(entries) == 0 {
			return nil, fmt.Errorf("authoritative source-binding scan made no progress")
		}
		after = append(after[:0], entries[len(entries)-1].Key...)
	}
}

func (store *SchemaStore) authoritativeCrawlMutations(ctx context.Context, transaction *Transaction, claim AuthoritativeCrawlClaim, identities []schema.ParsedKey, bindings map[string]schema.AuthoritativeSourceBindingRecord, commit, analyticsGeneration uint64) ([]Mutation, error) {
	debtFree := true
	for _, key := range claim.DebtKeys {
		parsed, err := schema.ParseKey(key)
		if err != nil || parsed.Kind != schema.KeyCrawlDebt {
			return nil, fmt.Errorf("invalid authoritative crawl debt key")
		}
		value, found, err := transaction.Get(ctx, key)
		if err != nil {
			return nil, err
		}
		if found {
			debt, err := schema.UnmarshalCrawlDebtRecord(value)
			if err != nil {
				return nil, err
			}
			debtFree = debtFree && debt.Status == schema.DebtResolved
		}
	}
	proof := schema.AuthoritativeCrawlProofRecord{ScopeID: claim.ScopeID, RootFSID: claim.RootFSID, RootInode: claim.RootInode, StartFence: claim.StartFence, EndCommit: commit, CompletedAt: time.Now().UnixNano(), Complete: claim.Complete, DebtFree: debtFree}
	proofValue, err := proof.MarshalBinary()
	if err != nil {
		return nil, err
	}
	mutations := []Mutation{{Key: schema.AuthoritativeCrawlProofKey(claim.ScopeID, commit), Value: proofValue}}
	observed := make(map[string]schema.ParsedKey, len(identities))
	var analyticsOrdinal uint32
	for _, identity := range identities {
		priorKey, prior, found := currentSourceBinding(bindings, identity.FSID, identity.Inode)
		if found {
			value, exists, err := transaction.Get(ctx, priorKey)
			if err != nil {
				return nil, err
			}
			if exists {
				prior, err = schema.UnmarshalAuthoritativeSourceBindingRecord(value)
				if err != nil {
					return nil, err
				}
			}
		}
		generation := identity.Revision
		continuity := schema.AnalyticsContinuityUnknown
		newGeneration := !found
		sourceStateChanged := !found || prior.State != schema.AuthoritativeSourceLive
		if found && prior.State == schema.AuthoritativeSourceLive {
			generation, continuity, newGeneration = prior.Generation, prior.Continuity, false
		} else if found && prior.State == schema.AuthoritativeSourceDeleted {
			continuity = schema.AnalyticsContinuityProven
			newGeneration = true
		}
		key := schema.AuthoritativeSourceBindingKey(claim.ScopeID, identity.FSID, identity.Inode, generation)
		observed[string(key)] = identity
		binding := schema.AuthoritativeSourceBindingRecord{Generation: generation, Revision: identity.Revision, State: schema.AuthoritativeSourceLive, Continuity: continuity, LastObservedCommit: commit}
		encoded, err := binding.MarshalBinary()
		if err != nil {
			return nil, err
		}
		mutations = append(mutations, Mutation{Key: key, Value: encoded})
		if analyticsGeneration != 0 && sourceStateChanged {
			var delta schema.AnalyticsDeltaRecord
			if newGeneration {
				delta = schema.AnalyticsDeltaRecord{Kind: schema.AnalyticsDeltaCreation, FSID: identity.FSID, Inode: identity.Inode, IdentityGeneration: generation, Revision: identity.Revision, CreatedAt: time.Now().UnixNano(), CreationBasis: schema.AnalyticsFirstSeen, IdentityContinuity: continuity, State: schema.AnalyticsLive, ClassificationEpoch: analyticsGeneration}
			} else {
				delta = schema.AnalyticsDeltaRecord{Kind: schema.AnalyticsDeltaSourceState, FSID: identity.FSID, Inode: identity.Inode, IdentityGeneration: generation, Revision: identity.Revision, IdentityContinuity: continuity, State: schema.AnalyticsLive, ClassificationEpoch: analyticsGeneration}
			}
			value, err := delta.MarshalBinary()
			if err != nil {
				return nil, err
			}
			mutations = append(mutations, Mutation{Key: schema.AnalyticsDeltaKey(commit, analyticsOrdinal), Value: value})
			analyticsOrdinal++
		}
	}
	for keyString, prior := range bindings {
		if _, found := observed[keyString]; found || prior.State == schema.AuthoritativeSourceDeleted {
			continue
		}
		key := []byte(keyString)
		if value, found, err := transaction.Get(ctx, key); err != nil {
			return nil, err
		} else if found {
			prior, err = schema.UnmarshalAuthoritativeSourceBindingRecord(value)
			if err != nil {
				return nil, err
			}
		}
		state := schema.AuthoritativeSourceUnknown
		analyticsState := schema.AnalyticsUnknown
		if proof.Complete && proof.DebtFree && prior.LastObservedCommit <= claim.StartFence {
			state = schema.AuthoritativeSourceDeleted
			analyticsState = schema.AnalyticsDeleted
			if prior.State == schema.AuthoritativeSourceLive && !hasUnknownGeneration(bindings, keyString) {
				prior.Continuity = schema.AnalyticsContinuityProven
			}
		} else {
			prior.Continuity = schema.AnalyticsContinuityUnknown
		}
		prior.State, prior.LastObservedCommit = state, commit
		encoded, err := prior.MarshalBinary()
		if err != nil {
			return nil, err
		}
		mutations = append(mutations, Mutation{Key: key, Value: encoded})
		if analyticsGeneration != 0 {
			parsed, _ := schema.ParseKey(key)
			delta := schema.AnalyticsDeltaRecord{Kind: schema.AnalyticsDeltaSourceState, FSID: parsed.FSID, Inode: parsed.Inode, IdentityGeneration: prior.Generation, Revision: prior.Revision, IdentityContinuity: prior.Continuity, State: analyticsState, ClassificationEpoch: analyticsGeneration}
			value, err := delta.MarshalBinary()
			if err != nil {
				return nil, err
			}
			mutations = append(mutations, Mutation{Key: schema.AnalyticsDeltaKey(commit, analyticsOrdinal), Value: value})
			analyticsOrdinal++
		}
	}
	return mutations, nil
}

func hasUnknownGeneration(bindings map[string]schema.AuthoritativeSourceBindingRecord, currentKey string) bool {
	current, err := schema.ParseKey([]byte(currentKey))
	if err != nil {
		return true
	}
	for keyString, binding := range bindings {
		if keyString == currentKey || binding.State != schema.AuthoritativeSourceUnknown {
			continue
		}
		parsed, err := schema.ParseKey([]byte(keyString))
		if err == nil && parsed.FSID == current.FSID && parsed.Inode == current.Inode {
			return true
		}
	}
	return false
}

func currentSourceBinding(bindings map[string]schema.AuthoritativeSourceBindingRecord, fsid uint32, inode uint64) ([]byte, schema.AuthoritativeSourceBindingRecord, bool) {
	var selectedKey []byte
	var selected schema.AuthoritativeSourceBindingRecord
	for keyString, record := range bindings {
		parsed, err := schema.ParseKey([]byte(keyString))
		if err != nil || parsed.FSID != fsid || parsed.Inode != inode {
			continue
		}
		if selectedKey == nil || sourceBindingPriority(record.State) > sourceBindingPriority(selected.State) || sourceBindingPriority(record.State) == sourceBindingPriority(selected.State) && record.LastObservedCommit > selected.LastObservedCommit {
			selectedKey, selected = []byte(keyString), record
		}
	}
	return selectedKey, selected, selectedKey != nil
}

func sourceBindingPriority(state schema.AuthoritativeSourceState) int {
	if state == schema.AuthoritativeSourceLive {
		return 2
	}
	if state == schema.AuthoritativeSourceUnknown {
		return 1
	}
	return 0
}

// ForgetSnapshot atomically removes logical snapshot membership and emits
// ordered analytics triggers. Physical pack lifecycle is deliberately absent.
func (store *SchemaStore) ForgetSnapshot(ctx context.Context, snapshotID schema.ID) error {
	value, found, err := store.Get(ctx, schema.SnapshotKey(snapshotID))
	if err != nil || !found {
		return err
	}
	record, err := schema.UnmarshalSnapshotRecord(value)
	if err != nil {
		return err
	}
	rootKey := schema.DirectoryRevisionKey(record.RootFSID, record.RootInode, record.RootRevision)
	var identities []schema.ParsedKey
	if enabled, enabledErr := store.analyticsEnabled(ctx); enabledErr != nil {
		return enabledErr
	} else if enabled {
		identities, err = store.snapshotIdentities(ctx, rootKey)
		if err != nil {
			return err
		}
	}
	backoff := 100 * time.Microsecond
	for range revisionAllocationAttempts {
		err = store.forgetSnapshotOnce(ctx, snapshotID, record, identities)
		if status.Code(err) != codes.Aborted {
			return err
		}
		timer := time.NewTimer(backoff)
		select {
		case <-ctx.Done():
			timer.Stop()
			return ctx.Err()
		case <-timer.C:
		}
		backoff = min(backoff*2, 25*time.Millisecond)
	}
	return fmt.Errorf("forget snapshot: transaction conflict retry limit exceeded")
}

func (store *SchemaStore) forgetSnapshotOnce(ctx context.Context, snapshotID schema.ID, record schema.SnapshotRecord, identities []schema.ParsedKey) error {
	transaction, err := store.client.Begin(ctx)
	if err != nil {
		return err
	}
	fail := func(err error) error { rollbackTransaction(ctx, transaction); return err }
	if _, found, err := transaction.Get(ctx, schema.SnapshotKey(snapshotID)); err != nil {
		return fail(err)
	} else if !found {
		return transaction.Rollback(ctx)
	}
	next := uint64(1)
	if value, found, err := transaction.Get(ctx, schema.NextRevisionKey()); err != nil {
		return fail(err)
	} else if found {
		next, err = schema.UnmarshalNextRevision(value)
		if err != nil {
			return fail(err)
		}
	}
	if next == math.MaxUint64 {
		return fail(fmt.Errorf("repository revision sequence exhausted"))
	}
	nextValue, err := schema.MarshalNextRevision(next + 1)
	if err != nil {
		return fail(err)
	}
	puts := []Mutation{{Key: schema.NextRevisionKey(), Value: nextValue}}
	if metadataValue, found, getErr := transaction.Get(ctx, schema.AnalyticsMetadataKey()); getErr != nil {
		return fail(getErr)
	} else if found {
		metadata, decodeErr := schema.UnmarshalAnalyticsMetadataRecord(metadataValue)
		if decodeErr == nil && metadata.Enabled {
			for ordinal, identity := range identities {
				delta := schema.AnalyticsDeltaRecord{Kind: schema.AnalyticsDeltaRetainedReferences, FSID: identity.FSID, Inode: identity.Inode, IdentityGeneration: identity.Revision, Revision: next, State: schema.AnalyticsUnknown, ReferenceOperation: schema.AnalyticsReferencesDecrement, ClassificationEpoch: metadata.Generation}
				encoded, encodeErr := delta.MarshalBinary()
				if encodeErr != nil {
					return fail(encodeErr)
				}
				puts = append(puts, Mutation{Key: schema.AnalyticsDeltaKey(next, uint32(ordinal)), Value: encoded})
			}
		}
	}
	deletes := [][]byte{schema.SnapshotKey(snapshotID), schema.SnapshotCommitKey(record.CommitSequence, snapshotID)}
	if err := writeTransactionBatches(ctx, transaction, store.client.Limits(), puts, deletes); err != nil {
		return fail(err)
	}
	if err := transaction.Commit(ctx); err != nil {
		return fail(err)
	}
	return nil
}

func (store *SchemaStore) snapshotIdentities(ctx context.Context, rootKey []byte) ([]schema.ParsedKey, error) {
	identities, err := store.snapshotIdentityRevisions(ctx, rootKey, false)
	if err != nil {
		return nil, err
	}
	generations := map[identityKey][]uint64{}
	var after []byte
	for {
		entries, done, err := store.ScanPrefix(ctx, []byte("asb:"), after, 10_000)
		if err != nil {
			return nil, err
		}
		for _, entry := range entries {
			parsed, err := schema.ParseKey(entry.Key)
			if err != nil || parsed.Kind != schema.KeyAuthoritativeSourceBinding {
				return nil, fmt.Errorf("invalid authoritative source binding key %x", entry.Key)
			}
			generations[identityKey{parsed.FSID, parsed.Inode}] = append(generations[identityKey{parsed.FSID, parsed.Inode}], parsed.Generation)
		}
		if done {
			break
		}
		if len(entries) == 0 {
			return nil, fmt.Errorf("authoritative source-binding scan made no progress")
		}
		after = append(after[:0], entries[len(entries)-1].Key...)
	}
	for index := range identities {
		generation := uint64(0)
		for _, candidate := range generations[identityKey{identities[index].FSID, identities[index].Inode}] {
			if candidate <= identities[index].Revision && candidate > generation {
				generation = candidate
			}
		}
		if generation == 0 {
			items, _, err := store.ScanPrefix(ctx, schema.InodeRevisionPrefix(identities[index].FSID, identities[index].Inode), nil, 1)
			if err != nil || len(items) == 0 {
				return nil, errors.Join(err, fmt.Errorf("snapshot inode %d:%d has no revision", identities[index].FSID, identities[index].Inode))
			}
			parsed, err := schema.ParseKey(items[0].Key)
			if err != nil {
				return nil, err
			}
			generation = parsed.Revision
		}
		identities[index].Revision = generation
	}
	return identities, nil
}

func (store *SchemaStore) snapshotObservedIdentities(ctx context.Context, rootKey []byte) ([]schema.ParsedKey, error) {
	return store.snapshotIdentityRevisions(ctx, rootKey, false)
}

func (store *SchemaStore) snapshotIdentityRevisions(ctx context.Context, rootKey []byte, oldest bool) ([]schema.ParsedKey, error) {
	seenDirectories := map[string]struct{}{}
	identities := map[string]schema.ParsedKey{}
	var visit func([]byte) error
	visit = func(key []byte) error {
		if _, seen := seenDirectories[string(key)]; seen {
			return nil
		}
		seenDirectories[string(key)] = struct{}{}
		value, found, err := store.Get(ctx, key)
		if err != nil || !found {
			return errors.Join(err, fmt.Errorf("snapshot directory %x is missing", key))
		}
		directory, err := schema.UnmarshalDirectoryRevision(value)
		if err != nil {
			return err
		}
		for _, child := range directory.Children {
			parsed, err := schema.ParseKey(child.MetadataKey)
			if err != nil {
				return err
			}
			if parsed.Kind == schema.KeyDirectoryRevision {
				if err := visit(child.MetadataKey); err != nil {
					return err
				}
				continue
			}
			if parsed.Kind != schema.KeyInodeRevision {
				continue
			}
			generation := parsed
			if oldest {
				items, _, err := store.ScanPrefix(ctx, schema.InodeRevisionPrefix(parsed.FSID, parsed.Inode), nil, 1)
				if err != nil || len(items) == 0 {
					return errors.Join(err, fmt.Errorf("snapshot inode %d:%d has no revision", parsed.FSID, parsed.Inode))
				}
				generation, err = schema.ParseKey(items[0].Key)
				if err != nil {
					return err
				}
			}
			identities[string(schema.AnalyticsResidencyKey(parsed.FSID, parsed.Inode, generation.Revision))] = generation
		}
		return nil
	}
	if err := visit(rootKey); err != nil {
		return nil, err
	}
	result := make([]schema.ParsedKey, 0, len(identities))
	for _, identity := range identities {
		result = append(result, identity)
	}
	sort.Slice(result, func(i, j int) bool {
		if result[i].FSID != result[j].FSID {
			return result[i].FSID < result[j].FSID
		}
		if result[i].Inode != result[j].Inode {
			return result[i].Inode < result[j].Inode
		}
		return result[i].Revision < result[j].Revision
	})
	return result, nil
}

func (store *SchemaStore) analyticsEnabled(ctx context.Context) (bool, error) {
	value, found, err := store.Get(ctx, schema.AnalyticsMetadataKey())
	if err != nil || !found {
		return false, err
	}
	metadata, err := schema.UnmarshalAnalyticsMetadataRecord(value)
	if err != nil {
		return false, nil
	}
	return metadata.Enabled, nil
}

func snapshotTimeUnixNano(originalJSON []byte) int64 {
	var decoded struct {
		Time time.Time `json:"time"`
	}
	if len(originalJSON) == 0 || json.Unmarshal(originalJSON, &decoded) != nil || decoded.Time.IsZero() {
		return 0
	}
	return decoded.Time.UnixNano()
}

// CreateImmutable creates a historical record or verifies an identical retry.
// It never overwrites an existing key with different bytes.
func (store *SchemaStore) CreateImmutable(ctx context.Context, key, value []byte) error {
	parsed, err := schema.ParseKey(key)
	if err != nil {
		return err
	}
	switch parsed.Kind {
	case schema.KeyBlob, schema.KeyInodeRevision, schema.KeyDirectoryRevision, schema.KeySnapshot:
	case schema.KeyContentManifest:
		return fmt.Errorf("content manifests require CreateContentManifest")
	default:
		return fmt.Errorf("schema key is mutable and cannot use CreateImmutable")
	}
	if err := schema.ValidateValue(key, value); err != nil {
		return err
	}
	transaction, err := store.client.Begin(ctx)
	if err != nil {
		return err
	}
	existing, found, err := transaction.Get(ctx, key)
	if err != nil {
		rollbackTransaction(ctx, transaction)
		return err
	}
	if found {
		if rollbackErr := rollbackTransaction(ctx, transaction); rollbackErr != nil {
			return rollbackErr
		}
		if !bytes.Equal(existing, value) {
			return fmt.Errorf("immutable schema record already exists with different data")
		}
		return nil
	}
	if err := transaction.WriteBatch(ctx, []Mutation{{Key: key, Value: value}}, nil); err != nil {
		rollbackTransaction(ctx, transaction)
		return err
	}
	if err := transaction.Commit(ctx); err != nil {
		rollbackTransaction(ctx, transaction)
		return err
	}
	return nil
}

// CreateContentManifest atomically creates every immutable segment for one
// content-addressed ordered blob sequence, or verifies an identical retry.
func (store *SchemaStore) CreateContentManifest(ctx context.Context, ids []schema.ID) (schema.ID, error) {
	return store.PublishContentManifest(ctx, ids, nil, nil)
}

// PublishContentManifest atomically creates canonical immutable segments and
// applies their mutable reverse-reference updates.
func (store *SchemaStore) PublishContentManifest(ctx context.Context, ids []schema.ID, relatedPuts []Mutation, relatedDeletes [][]byte) (schema.ID, error) {
	if err := validateRelatedMutations(relatedPuts, relatedDeletes); err != nil {
		return schema.ID{}, err
	}
	manifestID, segments, err := schema.SegmentContent(ids, schema.DefaultContentSegmentIDs)
	if err != nil {
		return schema.ID{}, err
	}
	if _, err := schema.AssembleContent(manifestID, append([]schema.ContentManifest(nil), segments...)); err != nil {
		return schema.ID{}, err
	}
	keys := make([][]byte, len(segments))
	encoded := make([][]byte, len(segments))
	for index, segment := range segments {
		keys[index] = schema.ContentManifestKey(manifestID, uint32(index))
		encoded[index], err = segment.MarshalBinary()
		if err != nil {
			return schema.ID{}, err
		}
	}
	transaction, err := store.client.Begin(ctx)
	if err != nil {
		return schema.ID{}, err
	}
	for start := 0; start < len(keys); {
		end, err := manifestBatchEnd(store.client.Limits(), keys, encoded, start)
		if err != nil {
			rollbackTransaction(ctx, transaction)
			return schema.ID{}, err
		}
		values, found, err := transaction.MultiGet(ctx, keys[start:end])
		if err != nil {
			rollbackTransaction(ctx, transaction)
			return schema.ID{}, err
		}
		puts := make([]Mutation, 0, end-start)
		for offset := range keys[start:end] {
			index := start + offset
			if found[offset] {
				if !bytes.Equal(values[offset].Value, encoded[index]) {
					rollbackTransaction(ctx, transaction)
					return schema.ID{}, fmt.Errorf("immutable content manifest segment already exists with different data")
				}
				continue
			}
			puts = append(puts, Mutation{Key: keys[index], Value: encoded[index]})
		}
		if len(puts) > 0 {
			if err := transaction.WriteBatch(ctx, puts, nil); err != nil {
				rollbackTransaction(ctx, transaction)
				return schema.ID{}, err
			}
		}
		start = end
	}
	if len(relatedPuts) > 0 || len(relatedDeletes) > 0 {
		if err := writeTransactionBatches(ctx, transaction, store.client.Limits(), relatedPuts, relatedDeletes); err != nil {
			rollbackTransaction(ctx, transaction)
			return schema.ID{}, err
		}
	}
	if err := transaction.Commit(ctx); err != nil {
		rollbackTransaction(ctx, transaction)
		return schema.ID{}, err
	}
	return manifestID, nil
}

func manifestBatchEnd(limits Limits, keys, values [][]byte, start int) (int, error) {
	if limits.MaxBatchItems == 0 || limits.MaxMessageBytes < 128 {
		return 0, fmt.Errorf("vaulticdb advertised insufficient manifest batch limits")
	}
	maxBytes := uint64(limits.MaxMessageBytes) / 2
	used := uint64(0)
	end := start
	for end < len(keys) && uint64(end-start) < uint64(limits.MaxBatchItems) {
		size := uint64(len(keys[end])) + uint64(len(values[end])) + 32
		if size > maxBytes {
			return 0, fmt.Errorf("content manifest segment exceeds daemon message limit")
		}
		if used+size > maxBytes {
			break
		}
		used += size
		end++
	}
	if end == start {
		return 0, fmt.Errorf("content manifest batch made no progress")
	}
	return end, nil
}

// PublishRevision atomically creates an immutable revision and advances its
// current pointer. A retry with identical revision bytes is idempotent.
func (store *SchemaStore) PublishRevision(ctx context.Context, currentKey, revisionKey, revisionValue []byte, revision uint64) error {
	return store.PublishRevisionBatch(ctx, currentKey, revisionKey, revisionValue, revision, nil, nil)
}

// PublishRevisionBatch atomically creates an immutable revision, advances its
// current pointer, and applies corresponding mutable reverse-reference data.
func (store *SchemaStore) PublishRevisionBatch(ctx context.Context, currentKey, revisionKey, revisionValue []byte, revision uint64, relatedPuts []Mutation, relatedDeletes [][]byte) error {
	if err := validateRelatedMutations(relatedPuts, relatedDeletes); err != nil {
		return err
	}
	current, err := schema.CurrentPointer{Revision: revision, RecordKey: revisionKey}.MarshalBinary()
	if err != nil {
		return err
	}
	currentParsed, err := schema.ParseKey(currentKey)
	if err != nil {
		return err
	}
	parsed, err := schema.ParseKey(revisionKey)
	validPair := currentParsed.FSID == parsed.FSID && currentParsed.Inode == parsed.Inode &&
		((currentParsed.Kind == schema.KeyCurrentInode && parsed.Kind == schema.KeyInodeRevision) ||
			(currentParsed.Kind == schema.KeyCurrentDirectory && parsed.Kind == schema.KeyDirectoryRevision))
	if err != nil || parsed.Revision != revision || !validPair {
		return fmt.Errorf("revision key does not match revision %d", revision)
	}
	if err := schema.ValidateValue(revisionKey, revisionValue); err != nil {
		return err
	}
	transaction, err := store.client.Begin(ctx)
	if err != nil {
		return err
	}
	existing, found, err := transaction.Get(ctx, revisionKey)
	if err != nil {
		rollbackTransaction(ctx, transaction)
		return err
	}
	if found && !bytes.Equal(existing, revisionValue) {
		rollbackTransaction(ctx, transaction)
		return fmt.Errorf("immutable revision already exists with different data")
	}
	currentValue, currentFound, err := transaction.Get(ctx, currentKey)
	if err != nil {
		rollbackTransaction(ctx, transaction)
		return err
	}
	if currentFound {
		pointer, decodeErr := schema.UnmarshalCurrentPointer(currentValue)
		if decodeErr != nil {
			rollbackTransaction(ctx, transaction)
			return decodeErr
		}
		if pointer.Revision > revision {
			rollbackTransaction(ctx, transaction)
			return fmt.Errorf("current revision %d is newer than %d", pointer.Revision, revision)
		}
	}
	puts := []Mutation{{Key: currentKey, Value: current}}
	if !found {
		puts = append(puts, Mutation{Key: revisionKey, Value: revisionValue})
	}
	puts = append(puts, relatedPuts...)
	if err := writeTransactionBatches(ctx, transaction, store.client.Limits(), puts, relatedDeletes); err != nil {
		rollbackTransaction(ctx, transaction)
		return err
	}
	if err := transaction.Commit(ctx); err != nil {
		rollbackTransaction(ctx, transaction)
		return err
	}
	return nil
}

// PublishReconciledRevision atomically publishes a verified metadata revision,
// content manifests, reverse references, reference counters, and debt
// resolution. Serializable conflicts retry the complete read/modify/write.
func (store *SchemaStore) PublishReconciledRevision(ctx context.Context, reconciled ReconciledRevision) error {
	backoff := 100 * time.Microsecond
	for range revisionAllocationAttempts {
		err := store.publishReconciledRevisionOnce(ctx, reconciled)
		if status.Code(err) != codes.Aborted {
			return err
		}
		timer := time.NewTimer(backoff)
		select {
		case <-ctx.Done():
			timer.Stop()
			return ctx.Err()
		case <-timer.C:
		}
		backoff = min(backoff*2, 25*time.Millisecond)
	}
	return fmt.Errorf("publish reconciled revision: transaction conflict retry limit exceeded")
}

func (store *SchemaStore) publishReconciledRevisionOnce(ctx context.Context, reconciled ReconciledRevision) error {
	currentValue, err := (schema.CurrentPointer{Revision: reconciled.Revision, RecordKey: reconciled.RevisionKey}).MarshalBinary()
	if err != nil {
		return err
	}
	currentParsed, err := schema.ParseKey(reconciled.CurrentKey)
	if err != nil {
		return err
	}
	revisionParsed, err := schema.ParseKey(reconciled.RevisionKey)
	if err != nil || reconciled.Revision == 0 || revisionParsed.Revision != reconciled.Revision ||
		currentParsed.FSID != revisionParsed.FSID || currentParsed.Inode != revisionParsed.Inode ||
		!((currentParsed.Kind == schema.KeyCurrentInode && revisionParsed.Kind == schema.KeyInodeRevision) ||
			(currentParsed.Kind == schema.KeyCurrentDirectory && revisionParsed.Kind == schema.KeyDirectoryRevision)) {
		return fmt.Errorf("reconciled revision key mismatch")
	}
	if err := schema.ValidateValue(reconciled.RevisionKey, reconciled.RevisionValue); err != nil {
		return err
	}
	if currentParsed.Kind == schema.KeyCurrentDirectory && len(reconciled.ContentIDs) != 0 {
		return fmt.Errorf("directory reconciliation cannot contain file content")
	}
	for _, key := range reconciled.DebtKeys {
		parsed, parseErr := schema.ParseKey(key)
		if parseErr != nil || parsed.Kind != schema.KeyCrawlDebt {
			return fmt.Errorf("reconciliation debt key is invalid")
		}
	}
	for _, mutation := range reconciled.RelatedPuts {
		if err := validateMutableKey(mutation.Key); err != nil {
			return err
		}
		if err := schema.ValidateValue(mutation.Key, mutation.Value); err != nil {
			return err
		}
	}

	transaction, err := store.client.Begin(ctx)
	if err != nil {
		return err
	}
	fail := func(err error) error {
		rollbackTransaction(ctx, transaction)
		return err
	}
	existingRevision, revisionFound, err := transaction.Get(ctx, reconciled.RevisionKey)
	if err != nil {
		return fail(err)
	}
	if revisionFound && !bytes.Equal(existingRevision, reconciled.RevisionValue) {
		return fail(fmt.Errorf("immutable revision already exists with different data"))
	}

	var oldContent []schema.ID
	var oldManifestID schema.ID
	oldCurrent, currentFound, err := transaction.Get(ctx, reconciled.CurrentKey)
	if err != nil {
		return fail(err)
	}
	if currentFound {
		pointer, decodeErr := schema.UnmarshalCurrentPointer(oldCurrent)
		if decodeErr != nil {
			return fail(decodeErr)
		}
		if revisionFound && pointer.Revision == reconciled.Revision && bytes.Equal(pointer.RecordKey, reconciled.RevisionKey) {
			return transaction.Rollback(ctx)
		}
		if pointer.Revision > reconciled.Revision {
			return fail(fmt.Errorf("current revision %d is newer than %d", pointer.Revision, reconciled.Revision))
		}
		if currentParsed.Kind == schema.KeyCurrentInode {
			value, found, getErr := transaction.Get(ctx, pointer.RecordKey)
			if getErr != nil {
				return fail(getErr)
			}
			if !found {
				return fail(fmt.Errorf("current inode revision is missing"))
			}
			record, decodeErr := schema.UnmarshalInodeRevision(value)
			if decodeErr != nil {
				return fail(decodeErr)
			}
			oldContent, err = transactionContentIDs(ctx, transaction, record)
			if err != nil {
				return fail(err)
			}
			if record.ContentMode == schema.ContentManifestRef {
				oldManifestID = record.ContentManifestID
			}
		}
	}

	puts := map[string]Mutation{string(reconciled.CurrentKey): {Key: reconciled.CurrentKey, Value: currentValue}}
	if !revisionFound {
		puts[string(reconciled.RevisionKey)] = Mutation{Key: reconciled.RevisionKey, Value: reconciled.RevisionValue}
	}
	manifestID, segments, err := reconciledManifest(reconciled.ContentIDs)
	if err != nil {
		return fail(err)
	}
	for index, segment := range segments {
		key := schema.ContentManifestKey(manifestID, uint32(index))
		encoded, encodeErr := segment.MarshalBinary()
		if encodeErr != nil {
			return fail(encodeErr)
		}
		existing, found, getErr := transaction.Get(ctx, key)
		if getErr != nil {
			return fail(getErr)
		}
		if found && !bytes.Equal(existing, encoded) {
			return fail(fmt.Errorf("immutable content manifest segment already exists with different data"))
		}
		if !found {
			puts[string(key)] = Mutation{Key: key, Value: encoded}
		}
	}

	oldUnique := uniqueSchemaIDs(oldContent)
	newUnique := uniqueSchemaIDs(reconciled.ContentIDs)
	newSet := make(map[schema.ID]struct{}, len(newUnique))
	for _, id := range newUnique {
		newSet[id] = struct{}{}
	}
	for _, id := range oldUnique {
		if _, remains := newSet[id]; remains {
			continue
		}
		key := schema.ReverseInodeKey(id, currentParsed.FSID, currentParsed.Inode)
		value, encodeErr := (schema.ReverseInodeRecord{LatestRevision: reconciled.Revision, State: schema.ReferenceHistorical}).MarshalBinary()
		if encodeErr != nil {
			return fail(encodeErr)
		}
		puts[string(key)] = Mutation{Key: key, Value: value}
		countKey := schema.ReferenceCountKey(id)
		count, countErr := transactionReferenceCount(ctx, transaction, puts, countKey)
		if countErr != nil {
			return fail(countErr)
		}
		count.UpdateSequence = reconciled.Revision
		encoded, encodeErr := count.MarshalBinary()
		if encodeErr != nil {
			return fail(encodeErr)
		}
		puts[string(countKey)] = Mutation{Key: countKey, Value: encoded}
	}
	if oldManifestID != (schema.ID{}) && oldManifestID != manifestID {
		for _, id := range oldUnique {
			key := schema.ReverseManifestKey(id, oldManifestID)
			value, found, getErr := transaction.Get(ctx, key)
			if getErr != nil {
				return fail(getErr)
			}
			if !found {
				continue
			}
			reverse, decodeErr := schema.UnmarshalReverseManifestRecord(value)
			if decodeErr != nil {
				return fail(decodeErr)
			}
			reverse.State = schema.ReferenceHistorical
			encoded, encodeErr := reverse.MarshalBinary()
			if encodeErr != nil {
				return fail(encodeErr)
			}
			puts[string(key)] = Mutation{Key: key, Value: encoded}
		}
	}
	for _, id := range newUnique {
		key := schema.ReverseInodeKey(id, currentParsed.FSID, currentParsed.Inode)
		_, found, getErr := transaction.Get(ctx, key)
		if getErr != nil {
			return fail(getErr)
		}
		value, encodeErr := (schema.ReverseInodeRecord{LatestRevision: reconciled.Revision, State: schema.ReferenceCurrent}).MarshalBinary()
		if encodeErr != nil {
			return fail(encodeErr)
		}
		puts[string(key)] = Mutation{Key: key, Value: value}
		countKey := schema.ReferenceCountKey(id)
		count, countErr := transactionReferenceCount(ctx, transaction, puts, countKey)
		if countErr != nil {
			return fail(countErr)
		}
		occurrences := countID(reconciled.ContentIDs, id)
		if math.MaxUint64-count.TotalReferences < occurrences || count.DistinctRevisions == math.MaxUint64 || (!found && count.DistinctInodes == math.MaxUint64) {
			return fail(fmt.Errorf("reference count overflow"))
		}
		count.TotalReferences += occurrences
		count.DistinctRevisions++
		if !found {
			count.DistinctInodes++
		}
		count.UpdateSequence = reconciled.Revision
		encoded, encodeErr := count.MarshalBinary()
		if encodeErr != nil {
			return fail(encodeErr)
		}
		puts[string(countKey)] = Mutation{Key: countKey, Value: encoded}
	}

	if len(segments) > 0 {
		segmentByID := make(map[schema.ID]uint32, len(newUnique))
		for index, id := range reconciled.ContentIDs {
			if _, found := segmentByID[id]; !found {
				segmentByID[id] = uint32(index / schema.DefaultContentSegmentIDs)
			}
		}
		for id, segment := range segmentByID {
			key := schema.ReverseManifestKey(id, manifestID)
			_, found, getErr := transaction.Get(ctx, key)
			if getErr != nil {
				return fail(getErr)
			}
			value, encodeErr := (schema.ReverseManifestRecord{Segment: segment, State: schema.ReferenceCurrent}).MarshalBinary()
			if encodeErr != nil {
				return fail(encodeErr)
			}
			puts[string(key)] = Mutation{Key: key, Value: value}
			if !found {
				countKey := schema.ReferenceCountKey(id)
				count, countErr := transactionReferenceCount(ctx, transaction, puts, countKey)
				if countErr != nil {
					return fail(countErr)
				}
				if count.TotalReferences == math.MaxUint64 || count.DistinctManifests == math.MaxUint64 {
					return fail(fmt.Errorf("reference count overflow"))
				}
				count.TotalReferences++
				count.DistinctManifests++
				count.UpdateSequence = reconciled.Revision
				encoded, encodeErr := count.MarshalBinary()
				if encodeErr != nil {
					return fail(encodeErr)
				}
				puts[string(countKey)] = Mutation{Key: countKey, Value: encoded}
			}
		}
	}

	for _, key := range reconciled.DebtKeys {
		value, found, getErr := transaction.Get(ctx, key)
		if getErr != nil {
			return fail(getErr)
		}
		if !found {
			continue
		}
		debt, decodeErr := schema.UnmarshalCrawlDebtRecord(value)
		if decodeErr != nil {
			return fail(decodeErr)
		}
		debt.Status = schema.DebtResolved
		debt.ErrorClass = ""
		debt.LastAttemptUnixNano = time.Now().UnixNano()
		encoded, encodeErr := debt.MarshalBinary()
		if encodeErr != nil {
			return fail(encodeErr)
		}
		puts[string(key)] = Mutation{Key: key, Value: encoded}
	}
	for _, mutation := range reconciled.RelatedPuts {
		puts[string(mutation.Key)] = mutation
	}
	if currentParsed.Kind == schema.KeyCurrentInode && !currentFound {
		metadataValue, enabled, getErr := transaction.Get(ctx, schema.AnalyticsMetadataKey())
		if getErr != nil {
			return fail(getErr)
		}
		if enabled {
			metadata, decodeErr := schema.UnmarshalAnalyticsMetadataRecord(metadataValue)
			if decodeErr == nil && metadata.Enabled {
				revision, decodeErr := schema.UnmarshalInodeRevision(reconciled.RevisionValue)
				if decodeErr != nil {
					return fail(decodeErr)
				}
				delta := schema.AnalyticsDeltaRecord{
					Kind: schema.AnalyticsDeltaCreation, FSID: revisionParsed.FSID, Inode: revisionParsed.Inode,
					IdentityGeneration: reconciled.Revision, Revision: reconciled.Revision,
					UID: revision.UID, GID: revision.GID, Known: revision.Known, LogicalSize: revision.Size,
					CreatedAt: time.Now().UnixNano(), CreationBasis: schema.AnalyticsFirstSeen,
					IdentityContinuity: schema.AnalyticsContinuityUnknown, State: schema.AnalyticsLive,
					ClassificationEpoch: metadata.Generation,
				}
				encoded, encodeErr := delta.MarshalBinary()
				if encodeErr != nil {
					return fail(fmt.Errorf("encode analytics outbox delta: %w", encodeErr))
				}
				key := schema.AnalyticsDeltaKey(reconciled.Revision, 0)
				puts[string(key)] = Mutation{Key: key, Value: encoded}
			}
		}
	}

	// Publish hardlink reference records for multi-parent inodes.
	if reconciled.HasMultipleParents && len(reconciled.HardlinkParents) > 0 {
		hrRec := schema.HardlinkRefsRecord{
			FSID: revisionParsed.FSID, Inode: revisionParsed.Inode, Revision: reconciled.Revision,
			Parents: reconciled.HardlinkParents, Freshness: schema.FreshnessVerified,
		}
		hrEncoded, hrErr := hrRec.MarshalBinary()
		if hrErr != nil {
			return fail(hrErr)
		}
		hrKey := schema.HardlinkRefsKey(revisionParsed.FSID, revisionParsed.Inode, reconciled.Revision)
		puts[string(hrKey)] = Mutation{Key: hrKey, Value: hrEncoded}
	}

	mutations := make([]Mutation, 0, len(puts))
	for _, mutation := range puts {
		mutations = append(mutations, mutation)
	}
	sort.Slice(mutations, func(left, right int) bool { return bytes.Compare(mutations[left].Key, mutations[right].Key) < 0 })
	if err := writeTransactionBatches(ctx, transaction, store.client.Limits(), mutations, nil); err != nil {
		return fail(err)
	}
	if err := transaction.Commit(ctx); err != nil {
		rollbackTransaction(ctx, transaction)
		return err
	}
	return nil
}

func reconciledManifest(ids []schema.ID) (schema.ID, []schema.ContentManifest, error) {
	if len(ids) <= schema.MaxInlineContentIDs {
		return schema.ID{}, nil, nil
	}
	return schema.SegmentContent(ids, schema.DefaultContentSegmentIDs)
}

func transactionContentIDs(ctx context.Context, transaction *Transaction, record schema.InodeRevision) ([]schema.ID, error) {
	switch record.ContentMode {
	case schema.ContentNone:
		return nil, nil
	case schema.ContentInline:
		return append([]schema.ID(nil), record.ContentIDs...), nil
	case schema.ContentManifestRef:
		segmentCount := (uint64(record.ContentCount) + schema.DefaultContentSegmentIDs - 1) / schema.DefaultContentSegmentIDs
		segments := make([]schema.ContentManifest, segmentCount)
		for index := range segments {
			value, found, err := transaction.Get(ctx, schema.ContentManifestKey(record.ContentManifestID, uint32(index)))
			if err != nil {
				return nil, err
			}
			if !found {
				return nil, fmt.Errorf("content manifest segment is missing")
			}
			segments[index], err = schema.UnmarshalContentManifest(value)
			if err != nil {
				return nil, err
			}
		}
		return schema.AssembleContent(record.ContentManifestID, segments)
	default:
		return nil, fmt.Errorf("invalid content mode")
	}
}

func transactionReferenceCount(ctx context.Context, transaction *Transaction, puts map[string]Mutation, key []byte) (schema.ReferenceCountRecord, error) {
	if mutation, found := puts[string(key)]; found {
		return schema.UnmarshalReferenceCountRecord(mutation.Value)
	}
	value, found, err := transaction.Get(ctx, key)
	if err != nil || !found {
		return schema.ReferenceCountRecord{}, err
	}
	return schema.UnmarshalReferenceCountRecord(value)
}

func uniqueSchemaIDs(ids []schema.ID) []schema.ID {
	seen := make(map[schema.ID]struct{}, len(ids))
	result := make([]schema.ID, 0, len(ids))
	for _, id := range ids {
		if _, found := seen[id]; found {
			continue
		}
		seen[id] = struct{}{}
		result = append(result, id)
	}
	return result
}

func countID(ids []schema.ID, target schema.ID) uint64 {
	var count uint64
	for _, id := range ids {
		if id == target {
			count++
		}
	}
	return count
}

func validateRelatedMutations(puts []Mutation, deletes [][]byte) error {
	if err := validateDistinctMutations(puts, deletes); err != nil {
		return err
	}
	for _, put := range puts {
		if err := validateMutableKey(put.Key); err != nil {
			return err
		}
		if err := schema.ValidateValue(put.Key, put.Value); err != nil {
			return err
		}
	}
	for _, key := range deletes {
		if err := validateMutableDeleteKey(key); err != nil {
			return err
		}
	}
	return nil
}

func writeTransactionBatches(ctx context.Context, transaction *Transaction, limits Limits, puts []Mutation, deletes [][]byte) error {
	if limits.MaxBatchItems == 0 || limits.MaxMessageBytes < 1024 {
		return fmt.Errorf("vaulticdb advertised insufficient transaction batch limits")
	}
	maxBytes := uint64(limits.MaxMessageBytes) - 512
	for putStart := 0; putStart < len(puts); {
		used := uint64(128)
		putEnd := putStart
		for putEnd < len(puts) && uint64(putEnd-putStart) < uint64(limits.MaxBatchItems) {
			size := uint64(len(puts[putEnd].Key)+len(puts[putEnd].Value)) + 32
			if size > maxBytes {
				return fmt.Errorf("schema mutation exceeds daemon message limit")
			}
			if used+size > maxBytes {
				break
			}
			used += size
			putEnd++
		}
		if putEnd == putStart {
			return fmt.Errorf("schema mutation batch made no progress")
		}
		if err := transaction.WriteBatch(ctx, puts[putStart:putEnd], nil); err != nil {
			return err
		}
		putStart = putEnd
	}
	for deleteStart := 0; deleteStart < len(deletes); {
		used := uint64(128)
		deleteEnd := deleteStart
		for deleteEnd < len(deletes) && uint64(deleteEnd-deleteStart) < uint64(limits.MaxBatchItems) {
			size := uint64(len(deletes[deleteEnd])) + 16
			if size > maxBytes {
				return fmt.Errorf("schema delete exceeds daemon message limit")
			}
			if used+size > maxBytes {
				break
			}
			used += size
			deleteEnd++
		}
		if deleteEnd == deleteStart {
			return fmt.Errorf("schema delete batch made no progress")
		}
		if err := transaction.WriteBatch(ctx, nil, deletes[deleteStart:deleteEnd]); err != nil {
			return err
		}
		deleteStart = deleteEnd
	}
	return nil
}

func validateDistinctMutations(puts []Mutation, deletes [][]byte) error {
	seen := make(map[string]struct{}, len(puts)+len(deletes))
	for _, put := range puts {
		key := string(put.Key)
		if _, duplicate := seen[key]; duplicate {
			return fmt.Errorf("schema batch contains duplicate key")
		}
		seen[key] = struct{}{}
	}
	for _, deleteKey := range deletes {
		key := string(deleteKey)
		if _, duplicate := seen[key]; duplicate {
			return fmt.Errorf("schema batch contains duplicate key")
		}
		seen[key] = struct{}{}
	}
	return nil
}

// AllocateRevision atomically returns one durable, monotonically increasing
// repository revision sequence. Serializable conflicts are retried.
func (store *SchemaStore) AllocateRevision(ctx context.Context) (uint64, error) {
	key := schema.NextRevisionKey()
	backoff := 100 * time.Microsecond
	for range revisionAllocationAttempts {
		transaction, err := store.client.Begin(ctx)
		if err != nil {
			return 0, err
		}
		encoded, found, err := transaction.Get(ctx, key)
		if err != nil {
			rollbackTransaction(ctx, transaction)
			return 0, err
		}
		next := uint64(1)
		if found {
			next, err = schema.UnmarshalNextRevision(encoded)
			if err != nil {
				rollbackTransaction(ctx, transaction)
				return 0, err
			}
		}
		if next == math.MaxUint64 {
			rollbackTransaction(ctx, transaction)
			return 0, fmt.Errorf("repository revision sequence exhausted")
		}
		encodedNext, err := schema.MarshalNextRevision(next + 1)
		if err != nil {
			rollbackTransaction(ctx, transaction)
			return 0, err
		}
		if err := transaction.WriteBatch(ctx, []Mutation{{Key: key, Value: encodedNext}}, nil); err != nil {
			rollbackTransaction(ctx, transaction)
			return 0, err
		}
		if err := transaction.Commit(ctx); err != nil {
			rollbackTransaction(ctx, transaction)
			if status.Code(err) == codes.Aborted {
				timer := time.NewTimer(backoff)
				select {
				case <-ctx.Done():
					timer.Stop()
					return 0, ctx.Err()
				case <-timer.C:
				}
				backoff = min(backoff*2, 25*time.Millisecond)
				continue
			}
			return 0, err
		}
		return next, nil
	}
	return 0, fmt.Errorf("allocate repository revision: %w", errors.New("transaction conflict retry limit exceeded"))
}

func rollbackTransaction(ctx context.Context, transaction *Transaction) error {
	cleanupCtx, cancel := context.WithTimeout(context.WithoutCancel(ctx), defaultRPCDeadline)
	defer cancel()
	return transaction.Rollback(cleanupCtx)
}
